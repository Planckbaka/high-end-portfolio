import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadArticles } from "./article-pipeline.mjs";
import { renderFeed } from "../src/lib/feed-core.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const articles = await loadArticles(path.join(root, "content/articles"), root);

const indexEntries = articles.map(({ content: _content, ...summary }) => {
  void _content;
  return summary;
});

await fs.writeFile(path.join(root, "src/lib/articles-index.json"), JSON.stringify(indexEntries));

const contentDir = path.join(root, "src/lib/articles-content");
await fs.rm(contentDir, { recursive: true, force: true });
await fs.mkdir(contentDir, { recursive: true });

for (const article of articles) {
  await fs.writeFile(
    path.join(contentDir, `${article.slug}.json`),
    JSON.stringify({ content: article.content })
  );
}

const loaderLines = [
  "// Auto-generated by scripts/generate-articles-data.mjs — do not edit manually.",
  "export const articleContentLoaders: Record<",
  "  string,",
  "  () => Promise<{ default: { content: string } }>",
  "> = {",
  ...articles.map(
    (a) => `  ${JSON.stringify(a.slug)}: () => import(${JSON.stringify(`./${a.slug}.json`)}),`
  ),
  "};",
  "",
];
await fs.writeFile(path.join(contentDir, "index.ts"), loaderLines.join("\n"));

const site = {
  url: process.env.NEXT_PUBLIC_SITE_URL || "https://high-end-portfolio.1229773363.workers.dev",
  title: "Akiwayne | Backend & AI Engineering",
  description:
    "Notes on Go backends, Python engineering, and model inference. Implementations, reproducible experiments, and the decisions behind them.",
};
await fs.mkdir(path.join(root, "public"), { recursive: true });
await fs.writeFile(path.join(root, "public/feed.xml"), renderFeed(articles, site));

console.log(
  `Generated ${articles.length} published articles (split index + content modules) and full-text public/feed.xml.`
);
